def parse_param_address(param_name):
    """
    解析 HXX_YY 参数号到 Modbus 地址。
    规则: HXX_YY → (XX << 8) | YY = 0xXXYY

    Args:
        param_name: 参数号，如 "H06_03"

    Returns:
        int: Modbus 寄存器地址
    """
    name = param_name.strip().upper()
    if name in REGISTERS:
        return REGISTERS[name]
    if name.startswith("H") and "_" in name:
        parts = name[1:].split("_")
        if len(parts) == 2:
            hi = int(parts[0], 16)
            lo = int(parts[1], 16)
            return (hi << 8) | lo
    raise ValueError(f"无法解析参数号: {param_name}")
